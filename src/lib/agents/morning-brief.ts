/**
 * Run morning briefing for a foundry
 */
export async function runMorningBriefing(
  foundryId: string,
  founderId: string
): Promise<{
  success: boolean
  briefing?: MorningBriefing
  artifactId?: string
  error?: string
}> {
  try {
    // Generate the briefing
    const briefing = await generateMorningBriefing(foundryId, founderId)

    // Save as artifact
    const artifactId = await saveBriefingAsArtifact(foundryId, briefing, 'chief-of-staff' as any)

    // TODO: Send notification to founder (Telegram/Slack/Email)

    return {
      success: true,
      briefing,
      artifactId: artifactId || undefined
    }
  } catch (error) {
    console.error('[MorningBrief] Error running briefing:', error)
    return {
      success: false,
      error: error instanceof Error ? error.message : 'Unknown error'
    }
  }
}

/**
 * Get today's briefing for a foundry (cached)
 */
export async function getTodaysBriefing(
  foundryId: string
): Promise<MorningBriefing | null> {
  const today = new Date().toISOString().split('T')[0]

  const { data, error } = await supabase
    .from('agent_artifacts')
    .select('content, metadata')
    .eq('foundry_id', foundryId)
    .eq('content_type', 'report')
    .contains('metadata', { type: 'morning_briefing', briefing_date: today })
    .order('created_at', { ascending: false })
    .limit(1)
    .single()

  if (error || !data) {
    return null
  }

  // Parse sections from content
  const sections: BriefingSection[] = []
  const contentParts = data.content.split('\n\n---\n\n')

  for (const part of contentParts) {
    const match = part.match(/^## (.+)\n\n(.+)$/s)
    if (match) {
      sections.push({
        title: match[1],
        content: match[2]
      })
    }
  }

  return {
    date: data.metadata?.briefing_date,
    sections,
    generatedAt: data.metadata?.generated_at
  }
}
