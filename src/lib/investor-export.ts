/**
 * Generates a CSV string and triggers a browser download.
 */
export function exportInvestorsCSV(
  firms: InvestorFirm[],
  matchScores?: Record<string, number>
): void {
  const headers = [
    'Name', 'Type', 'Fund Size (GBP)', 'Cheque Min', 'Cheque Max',
    'Stage Focus', 'Sectors', 'HQ City', 'Active Deploying', 'Quality Score',
    'Match Score', 'Priority', 'BVCA Member',
  ]

  const rows = firms.map(f => {
    const a = f.attributes
    return [
      escapeCsv(f.title),
      escapeCsv(a.firm_type ?? ''),
      escapeCsv(a.fund_size_gbp?.toString() ?? ''),
      escapeCsv(a.cheque_range_gbp?.min?.toString() ?? ''),
      escapeCsv(a.cheque_range_gbp?.max?.toString() ?? ''),
      escapeCsv((a.stage_focus ?? []).join('; ')),
      escapeCsv((a.sectors ?? []).join('; ')),
      escapeCsv(a.hq_city ?? ''),
      a.is_active_deploying ? 'Yes' : 'No',
      escapeCsv(a.data_quality_score?.toFixed(1) ?? ''),
      escapeCsv(matchScores?.[f.id]?.toString() ?? ''),
      escapeCsv(a.outreach_priority ?? ''),
      a.bvca_member ? 'Yes' : 'No',
    ].join(',')
  })

  // GOTCHA: UTF-8 BOM (\uFEFF) needed for Windows Excel to correctly detect encoding
  const csv = '\uFEFF' + [headers.join(','), ...rows].join('\n')
  downloadBlob(csv, 'investor-directory.csv', 'text/csv;charset=utf-8')
}

function escapeCsv(value: string): string {
  // SECURITY: Neutralize formula injection (=, +, -, @, \t, \r can trigger formulas in Excel/Sheets)
  if (/^[=+\-@\t\r]/.test(value)) {
    value = "'" + value
  }
  if (value.includes(',') || value.includes('"') || value.includes('\n') || value.includes("'")) {
    return `"${value.replace(/"/g, '""')}"`
  }
  return value
}

function downloadBlob(content: string, filename: string, mimeType: string): void {
  const blob = new Blob([content], { type: mimeType })
  const url = URL.createObjectURL(blob)
  const a = document.createElement('a')
  a.href = url
  a.download = filename
  document.body.appendChild(a)
  a.click()
  document.body.removeChild(a)
  URL.revokeObjectURL(url)
}

