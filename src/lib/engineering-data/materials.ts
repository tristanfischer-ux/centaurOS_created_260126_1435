/** Find a material by exact ID or fuzzy name match */
export function findMaterial(query: string): MaterialProperty | undefined {
    const normalized = query.toLowerCase().trim()

    // 1. Exact ID match
    const byId = MATERIALS.find((m) => m.id === normalized)
    if (byId) return byId

    // 2. Exact name match (case-insensitive)
    const byName = MATERIALS.find((m) => m.name.toLowerCase() === normalized)
    if (byName) return byName

    // 3. Fuzzy: check if query is a substring of name or any common grade
    const bySubstring = MATERIALS.find(
        (m) =>
            m.name.toLowerCase().includes(normalized) ||
            m.common_grades.some((g) => g.toLowerCase().includes(normalized))
    )
    if (bySubstring) return bySubstring

    // 4. Fuzzy: check if all words in query appear in name
    const words = normalized.split(/\s+/)
    const byWords = MATERIALS.find((m) => {
        const nameLower = m.name.toLowerCase()
        return words.every((w) => nameLower.includes(w))
    })
    if (byWords) return byWords

    return undefined
}

/** List all material IDs and names */
export function listMaterials(): string {
    return MATERIALS.map((m) => `${m.id}: ${m.name}`).join("\n")
}

/** Get materials filtered by category */
export function getMaterialsByCategory(
    category: MaterialProperty["category"]
): MaterialProperty[] {
    return MATERIALS.filter((m) => m.category === category)
}

/** Search materials by name (case-insensitive substring) */
export function searchMaterials(query: string): MaterialProperty[] {
    const normalized = query.toLowerCase().trim()
    return MATERIALS.filter(
        (m) =>
            m.name.toLowerCase().includes(normalized) ||
            m.id.includes(normalized) ||
            m.common_grades.some((g) => g.toLowerCase().includes(normalized)) ||
            m.category.includes(normalized)
    )
}
