/**
 * Get agent-created objectives pending approval
 */
async function getPendingApprovals(foundryId: string): Promise<{ objectives: any[]; tasks: any[] }> {
  const [objectivesRes, tasksRes] = await Promise.all([
    supabase
      .from('objectives')
      .select('*')
      .eq('foundry_id', foundryId)
      .eq('agent_approved', false)
      .eq('created_by_agent_id', 'not', null)
      .order('created_at', { ascending: false }),
    supabase
      .from('tasks')
      .select('*')
      .eq('foundry_id', foundryId)
      .eq('agent_approved', false)
      .eq('created_by_agent_id', 'not', null)
      .order('created_at', { ascending: false })
  ])

  return {
    objectives: objectivesRes.data || [],
    tasks: tasksRes.data || []
  }
}

/**
 * Get blockers (overdue tasks assigned to agents)
 */
async function getAgentBlockers(foundryId: string): Promise<any[]> {
  const { data, error } = await supabase
    .from('tasks')
    .select('*, objectives(title)')
    .eq('foundry_id', foundryId)
    .eq('agent_approved', true)
    .eq('status', 'Blocked')
    .order('due_date', { ascending: true })

  if (error) {
    console.error('[MorningBrief] Error getting blockers:', error)
    return []
  }

  return data || []
}

/**
 * Get agent action log summary
 */
async function getAgentActivitySummary(foundryId: string, since: Date): Promise<{
  total: number
  byTier: Record<string, number>
  byAgent: Record<string, number>
}> {
  const { data, error } = await supabase
    .from('agent_action_log')
    .select('tier, agent_name, status')
    .eq('foundry_id', foundryId)
    .gte('created_at', since.toISOString())

  if (error) {
    console.error('[MorningBrief] Error getting activity:', error)
    return { total: 0, byTier: {}, byAgent: {} }
  }

  const byTier: Record<string, number> = {}
  const byAgent: Record<string, number> = {}

  for (const entry of data || []) {
    byTier[entry.tier] = (byTier[entry.tier] || 0) + 1
    byAgent[entry.agent_name || 'unknown'] = (byAgent[entry.agent_name || 'unknown'] || 0) + 1
  }

  return { total: data?.length || 0, byTier, byAgent }
}

/**
 * Get recent collaboration sessions
 */
async function getRecentCollaborations(foundryId: string, since: Date): Promise<any[]> {
  const { data, error } = await supabase
    .from('agent_collaboration_sessions')
    .select('*, agent_collaboration_contributions(*)')
    .eq('foundry_id', foundryId)
    .gte('created_at', since.toISOString())
    .in('status', ['completed', 'synthesizing'])
    .order('completed_at', { ascending: false })

  if (error) {
    console.error('[MorningBrief] Error getting collaborations:', error)
    return []
  }

  return data || []
}

