/**
 * Morning Briefing System
 *
 * Cal (Chief of Staff) generates daily morning briefings:
 * - What the AI team accomplished overnight
 * - Key insights and findings
 * - Blockers and issues needing attention
 * - Suggested agenda for the day
 *
 * @module agents/morning-brief
 */

import { supabase } from '@/lib/supabase/server'
import { sendAgentMessage, startCollaboration, addContribution, completeCollaboration } from './collaboration-hub'

// ============================================================================
// TYPES
// ============================================================================

export interface BriefingData {
  foundryId: string
  founderId: string
  date: string // YYYY-MM-DD
}

export interface BriefingSection {
  title: string
  content: string
  priority?: 'critical' | 'important' | 'info'
  actionItems?: string[]
}

export interface MorningBriefing {
  date: string
  sections: BriefingSection[]
  generatedAt: string
}

