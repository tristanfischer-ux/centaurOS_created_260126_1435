// ========================
// Brand Constants
// ========================

const ORANGE = 'FF4500'
const BLUE = '3B82F6'
const DARK_TEXT = '1E293B'
const NAVY_ACCENT = '1E293B' // Dark navy for board-pack cover
const MID_TEXT = '64748B'
const LIGHT_BG = 'F8FAFC'
const WHITE = 'FFFFFF'
const GREEN = '16A34A'
const RED = 'DC2626'

// ========================
// Helpers
