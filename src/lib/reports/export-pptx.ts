// INTENT: Reusable section title with an orange underline accent, matching
// the ForgeOS brand pattern used throughout the on-screen report renderer.
function addSectionTitle(slide: PptxGenJS.Slide, title: string): void {
  slide.addText(title, {
    x: 0.6,
    y: 0.35,
    w: 10,
    h: 0.5,
    fontSize: 24,
    fontFace: 'Helvetica Neue',
    bold: true,
    color: DARK_TEXT,
  })
  slide.addShape('rect', {
    x: 0.6,
    y: 0.85,
    w: 1.2,
    h: 0.04,
    fill: { color: ORANGE },
  })
}

function formatMetricValue(value: number, format: KPIMetric['format']): string {
  switch (format) {
    case 'percentage':
      return `${Math.round(value)}%`
    case 'number':
      return value.toLocaleString('en-US', { maximumFractionDigits: 0 })
    case 'decimal':
      return value.toLocaleString('en-US', {
        minimumFractionDigits: 1,
        maximumFractionDigits: 1,
      })
    default:
      return String(value)
  }
}

function healthColor(health: string): string {
  switch (health) {
    case 'on-track':
    case 'completed':
      return GREEN
    case 'at-risk':
      return ORANGE
    case 'off-track':
      return RED
    default:
      return MID_TEXT
  }
}

function formatDate(dateStr: string): string {
  const d = new Date(dateStr + 'T00:00:00')
  return d.toLocaleDateString('en-GB', { day: 'numeric', month: 'short' })
}

// INTENT: Board-pack template adds Confidential and slide numbers to every
// slide except the cover. Footer elements go in the bottom-left and bottom-right.
function addBoardPackFooter(
  slide: PptxGenJS.Slide,
  slideNum: number
): void {
  slide.addText('Confidential', {
    x: 0.6,
    y: 7.1,
    w: 3,
    h: 0.25,
    fontSize: 9,
    fontFace: 'Helvetica Neue',
    color: MID_TEXT,
  })
  slide.addText(String(slideNum), {
    x: 11.8,
    y: 7.1,
    w: 1.2,
    h: 0.25,
    fontSize: 9,
    fontFace: 'Helvetica Neue',
    color: MID_TEXT,
    align: 'right',
  })
}

