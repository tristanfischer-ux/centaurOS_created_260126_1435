/**
 * @file materials.ts — Engineering material properties database.
 *
 * @description Curated database of ~40 common engineering materials with
 * real mechanical, thermal, and manufacturing properties. Values sourced
 * from MatWeb, ASM International, and manufacturer datasheets.
 *
 * @related
 * - Process constraints: src/lib/engineering-data/processes.ts
 * - Standard parts: src/lib/engineering-data/standard-parts.ts
 * - Tool handlers: src/lib/agents/tools/handlers/engineering-compute.ts
 */

export interface MaterialProperty {
    /** Unique key for lookup (e.g., "al-6061-t6") */
    id: string
    /** Human-readable name (e.g., "Aluminum 6061-T6") */
    name: string
    /** Material category */
    category: "metal" | "polymer" | "composite" | "ceramic" | "elastomer"
    /** Density in kg/m3 */
    density_kg_m3: number
    /** Yield strength in MPa (null for brittle materials) */
    yield_strength_mpa: number | null
    /** Ultimate tensile strength in MPa */
    ultimate_strength_mpa: number
    /** Elastic (Young's) modulus in GPa */
    elastic_modulus_gpa: number
    /** Thermal conductivity in W/(m*K) */
    thermal_conductivity_w_mk: number
    /** Specific heat capacity in J/(kg*K) */
    specific_heat_j_kgk: number
    /** Melting point in C (null for polymers that degrade) */
    melting_point_c: number | null
    /** Glass transition temperature in C (polymers only) */
    glass_transition_c: number | null
    /** Heat deflection temperature in C at 0.45 MPa */
    hdt_c: number | null
    /** Coefficient of thermal expansion in um/(m*K) */
    cte_um_mk: number
    /** Poisson's ratio */
    poisson_ratio: number
    /** Machinability rating 0-100 (relative to free-machining steel = 100) */
    machinability_rating: number
    /** Compatibility with additive processes */
    printability: {
        fdm: boolean
        sla: boolean
        sls: boolean
        dmls: boolean
    }
    /** Cost range per kg in USD */
    cost_per_kg_usd: { low: number; high: number }
    /** Common grades/alloys */
    common_grades: string[]
    /** Engineering notes */
    notes: string
}

