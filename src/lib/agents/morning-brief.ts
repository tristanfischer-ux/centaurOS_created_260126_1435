/**
 * Generate the morning briefing content
 */
export async function generateMorningBriefing(
  foundryId: string,
  founderId: string
): Promise<MorningBriefing> {
  const now = new Date()
  const since = new Date(now.getTime() - 24 * 60 * 60 * 1000) // 24 hours ago

  // Gather all data in parallel
  const [
    completedTasks,
    completedObjectives,
    insights,
    pendingApprovals,
    blockers,
    activity,
    collaborations
  ] = await Promise.all([
    getOvernightTaskCompletions(foundryId, since),
    getOvernightObjectiveCompletions(foundryId, since),
    getOvernightInsights(foundryId, since),
    getPendingApprovals(foundryId),
    getAgentBlockers(foundryId),
    getAgentActivitySummary(foundryId, since),
    getRecentCollaborations(foundryId, since)
  ])

  const sections: BriefingSection[] = []

  // Section 1: Executive Summary
  const totalCompleted = completedTasks.length + completedObjectives.length
  const summaryContent = `Your AI team completed **${totalCompleted} items** in the last 24 hours, including ${completedObjectives.length} objectives and ${completedTasks.length} tasks.`

  sections.push({
    title: 'Executive Summary',
    content: summaryContent,
    priority: 'info'
  })

  // Section 2: Completed Objectives
  if (completedObjectives.length > 0) {
    const objList = completedObjectives
      .slice(0, 5)
      .map(o => `- ${o.title}`)
      .join('\n')

    sections.push({
      title: 'Completed Objectives',
      content: `${completedObjectives.length} objective${completedObjectives.length > 1 ? 's' : ''} completed:\n\n${objList}`,
      priority: 'important'
    })
  }

  // Section 3: Completed Tasks
  if (completedTasks.length > 0) {
    const taskList = completedTasks
      .slice(0, 10)
      .map(t => `- ${t.title} (${t.objectives?.title || 'No objective'})`)
      .join('\n')

    sections.push({
      title: 'Completed Tasks',
      content: `${completedTasks.length} task${completedTasks.length > 1 ? 's' : ''} completed:\n\n${taskList}`,
      priority: 'info'
    })
  }

  // Section 4: Key Insights
  if (insights.length > 0) {
    const criticalInsights = insights.filter((i: any) => i.urgency === 'critical')
    const importantInsights = insights.filter((i: any) => i.urgency === 'important')

    let insightContent = ''

    if (criticalInsights.length > 0) {
      insightContent += `**Critical (${criticalInsights.length}):**\n`
      insightContent += criticalInsights
        .slice(0, 3)
        .map((i: any) => `- ${i.title}: ${i.content?.substring(0, 100)}...`)
        .join('\n')
      insightContent += '\n\n'
    }

    if (importantInsights.length > 0) {
      insightContent += `**Important (${importantInsights.length}):**\n`
      insightContent += importantInsights
        .slice(0, 5)
        .map((i: any) => `- ${i.title}`)
        .join('\n')
    }

    sections.push({
      title: 'Key Insights',
      content: insightContent || `${insights.length} insights generated`,
      priority: criticalInsights.length > 0 ? 'critical' : 'important'
    })
  }

  // Section 5: Action Required (Pending Approvals)
  const { objectives: pendingObjectives, tasks: pendingTasks } = pendingApprovals
  const totalPending = pendingObjectives.length + pendingTasks.length

  if (totalPending > 0) {
    const actionItems: string[] = []

    if (pendingObjectives.length > 0) {
      actionItems.push(`${pendingObjectives.length} objective${pendingObjectives.length > 1 ? 's' : ''} need approval`)
    }
    if (pendingTasks.length > 0) {
      actionItems.push(`${pendingTasks.length} task${pendingTasks.length > 1 ? 's' : ''} need approval`)
    }

    sections.push({
      title: 'Action Required',
      content: `Your approval is needed:\n\n${actionItems.map(a => `- ${a}`).join('\n')}`,
      priority: 'important',
      actionItems
    })
  }

  // Section 6: Blockers
  if (blockers.length > 0) {
    const blockerList = blockers
      .slice(0, 5)
      .map(b => `- ${b.title}: ${b.description || 'No details'}`)
      .join('\n')

    sections.push({
      title: 'Blockers',
      content: `${blockers.length} task${blockers.length > 1 ? 's' : ''} blocked:\n\n${blockerList}`,
      priority: 'critical'
    })
  }

  // Section 7: Agent Activity Summary
  if (activity.total > 0) {
    const agentSummary = Object.entries(activity.byAgent)
      .map(([agent, count]) => `- ${agent}: ${count} actions`)
      .join('\n')

    sections.push({
      title: 'Team Activity',
      content: `**${activity.total} total actions** by your AI team:\n\n${agentSummary}`,
      priority: 'info'
    })
  }

  // Section 8: Today's Suggested Agenda
  const agendaItems: string[] = []

  if (totalPending > 0) {
    agendaItems.push('Review and approve pending AI-generated objectives and tasks')
  }
  if (blockers.length > 0) {
    agendaItems.push('Address blockers preventing AI team progress')
  }
  if (insights.length > 0) {
    agendaItems.push(`Review ${insights.length} new insights from overnight analysis`)
  }

  if (agendaItems.length > 0) {
    sections.push({
      title: "Today's Suggested Agenda",
      content: agendaItems.map(a => `- ${a}`).join('\n'),
      priority: 'important'
    })
  }

  return {
    date: now.toISOString().split('T')[0],
    sections,
    generatedAt: now.toISOString()
  }
}

