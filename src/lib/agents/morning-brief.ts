/**
 * Save briefing as artifact
 */
export async function saveBriefingAsArtifact(
  foundryId: string,
  briefing: MorningBriefing,
  authorAgentId: string
): Promise<string | null> {
  const content = briefing.sections
    .map(s => `## ${s.title}\n\n${s.content}`)
    .join('\n\n---\n\n')

  const { data, error } = await supabase
    .from('agent_artifacts')
    .insert({
      foundry_id: foundryId,
      created_by: authorAgentId,
      title: `Morning Briefing - ${briefing.date}`,
      content_type: 'report',
      content,
      metadata: {
        briefing_date: briefing.date,
        generated_at: briefing.generatedAt,
        type: 'morning_briefing'
      }
    })
    .select()
    .single()

  if (error) {
    console.error('[MorningBrief] Error saving artifact:', error)
    return null
  }

  return data?.id
}

